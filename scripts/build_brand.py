#!/usr/bin/env python3
"""Generate shared CSS from the same brand tokens used by the document builders."""
import json
import argparse
import shutil
from pathlib import Path

BRAND = Path(__file__).resolve().parents[1] / "website/brand"


def build():
    theme = json.loads((BRAND / "theme.json").read_text())
    rules = ["/* Generated by scripts/build_brand.py; edit theme.json for shared colors. */"]
    for family, weights in [("Montserrat", [(500, "Medium"), (700, "Bold")]),
                            ("Open Sans", [(400, "Regular"), (600, "SemiBold"), (700, "Bold")])]:
        for weight, style in weights:
            name = family.replace(" ", "")
            rules.append(f'''@font-face {{
  font-family: "{family}";
  src: url("fonts/{name}-{style}.ttf") format("truetype");
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
}}''')
    tokens = [f"  --{key}: #{theme[key]};" for key in
              ("orange", "blue", "dark", "ink", "muted", "line", "pale")]
    tokens += [f'  --heading-font: "{theme["heading_font"]}", sans-serif;',
               f'  --body-font: "{theme["body_font"]}", sans-serif;']
    rules.append(":root {\n" + "\n".join(tokens) + "\n}")
    (BRAND / "brand.css").write_text("\n".join(rules) + "\n")


def sync_dashboard():
    """Keep the independently served dashboard self-contained and usable offline."""
    assets = BRAND.parents[1] / "ui-dashboard/assets"
    destination = assets / "brand"
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copy2(BRAND / "brand.css", destination / "brand.css")
    for directory in ("fonts", "logos"):
        shutil.copytree(BRAND / directory, destination / directory, dirs_exist_ok=True)
    shutil.copy2(BRAND.parent / "favicon.svg", assets / "cipher-logo.svg")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dashboard", action="store_true", help="Also refresh the dashboard's bundled fonts, logos and CSS")
    args = parser.parse_args()
    build()
    if args.dashboard:
        sync_dashboard()
